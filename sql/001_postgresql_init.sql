-- ProjectPulse PostgreSQL schema v0.4
-- Jalankan hanya pada database projectpulse yang baru/kosong.
-- Gunakan transaction; role executor memerlukan CREATE TABLE privileges.
BEGIN;
CREATE TABLE IF NOT EXISTS divisions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL
);
CREATE TABLE IF NOT EXISTS departments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    division_id integer NOT NULL REFERENCES divisions(id) ON DELETE RESTRICT,
    name text NOT NULL
);
CREATE TABLE IF NOT EXISTS users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id integer NOT NULL REFERENCES departments(id) ON DELETE RESTRICT,
    full_name text NOT NULL,
    email text NOT NULL UNIQUE,
    role text NOT NULL,
    password_hash text NOT NULL DEFAULT '',
    reports_to_pm_user_id integer REFERENCES users(id) ON DELETE RESTRICT,
    is_active boolean NOT NULL DEFAULT TRUE
);
-- Model parity only. The hosted JWT flow does not create or use local_sessions.
CREATE TABLE IF NOT EXISTS local_sessions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash text NOT NULL UNIQUE,
    expires_at timestamp with time zone NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_local_sessions_expires_at ON local_sessions(expires_at);
CREATE TABLE IF NOT EXISTS projects (
    id text PRIMARY KEY,
    department_id integer NOT NULL REFERENCES departments(id) ON DELETE RESTRICT,
    pm_user_id integer NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    timeline_owner_user_id integer REFERENCES users(id) ON DELETE RESTRICT,
    requester_name text NOT NULL DEFAULT '',
    requester_department text NOT NULL DEFAULT '',
    current_status text NOT NULL DEFAULT 'Requirement',
    name text NOT NULL,
    description text NOT NULL DEFAULT '',
    status text NOT NULL DEFAULT 'Active',
    health text NOT NULL DEFAULT 'On Track',
    progress integer NOT NULL DEFAULT 0 CHECK (progress BETWEEN 0 AND 100),
    start_date date NOT NULL,
    baseline_end date NOT NULL,
    forecast_end date,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS req_counters (
    date_key text PRIMARY KEY,
    last_number integer NOT NULL CHECK(last_number BETWEEN 0 AND 999)
);
CREATE TABLE IF NOT EXISTS project_members (
    project_id text NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    user_id integer NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    project_role text NOT NULL DEFAULT 'BA',
    PRIMARY KEY(project_id,user_id)
);
CREATE TABLE IF NOT EXISTS milestones (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id text NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    name text NOT NULL,
    weight integer NOT NULL CHECK (weight BETWEEN 1 AND 100),
    progress integer NOT NULL DEFAULT 0 CHECK (progress BETWEEN 0 AND 100),
    planned_start date NOT NULL,
    planned_end date NOT NULL,
    forecast_end date,
    status text NOT NULL DEFAULT 'Not Started'
);
CREATE TABLE IF NOT EXISTS tasks (
    id text PRIMARY KEY,
    project_id text NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    milestone_id integer REFERENCES milestones(id) ON DELETE RESTRICT,
    owner_user_id integer NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    title text NOT NULL,
    description text NOT NULL DEFAULT '',
    status text NOT NULL DEFAULT 'To Do',
    priority text NOT NULL DEFAULT 'Medium',
    due_date date NOT NULL,
    version integer NOT NULL DEFAULT 1,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at timestamp with time zone
);
CREATE TABLE IF NOT EXISTS task_contributors (
    task_id text NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
    user_id integer NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    PRIMARY KEY(task_id,user_id)
);
CREATE TABLE IF NOT EXISTS issues (
    id text PRIMARY KEY,
    project_id text NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    task_id text REFERENCES tasks(id) ON DELETE RESTRICT,
    owner_user_id integer NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    title text NOT NULL,
    severity text NOT NULL DEFAULT 'Medium',
    status text NOT NULL DEFAULT 'Open',
    impact text NOT NULL DEFAULT '',
    action_plan text NOT NULL DEFAULT '',
    due_date date,
    updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS task_activities (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id text NOT NULL,
    task_id text NOT NULL,
    actor_user_id integer NOT NULL,
    action text NOT NULL,
    old_value text NOT NULL DEFAULT '',
    new_value text NOT NULL DEFAULT '',
    note text NOT NULL DEFAULT '',
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS project_baselines (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id text NOT NULL,
    revision integer NOT NULL,
    snapshot_json text NOT NULL DEFAULT '{}',
    reason text NOT NULL DEFAULT '',
    approved_by_user_id integer,
    approved_at timestamp with time zone
);
CREATE INDEX IF NOT EXISTS ix_users_reports_to_pm ON users(reports_to_pm_user_id);
CREATE INDEX IF NOT EXISTS ix_projects_department_id ON projects(department_id);
CREATE INDEX IF NOT EXISTS ix_projects_pm_user_id ON projects(pm_user_id);
CREATE INDEX IF NOT EXISTS ix_project_members_user_id ON project_members(user_id);
CREATE INDEX IF NOT EXISTS ix_milestones_project_id ON milestones(project_id);
CREATE INDEX IF NOT EXISTS ix_tasks_project_id_due_date ON tasks(project_id,due_date);
CREATE INDEX IF NOT EXISTS ix_tasks_owner_user_id ON tasks(owner_user_id);
CREATE INDEX IF NOT EXISTS ix_tasks_milestone_id ON tasks(milestone_id);
CREATE INDEX IF NOT EXISTS ix_task_contributors_user_id ON task_contributors(user_id);
CREATE INDEX IF NOT EXISTS ix_issues_project_id_status ON issues(project_id,status);
CREATE INDEX IF NOT EXISTS ix_issues_owner_user_id ON issues(owner_user_id);
CREATE INDEX IF NOT EXISTS ix_issues_task_id ON issues(task_id);
CREATE INDEX IF NOT EXISTS ix_task_activities_project_id_created_at ON task_activities(project_id,created_at);
COMMIT;
